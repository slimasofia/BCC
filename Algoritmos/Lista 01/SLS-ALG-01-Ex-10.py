import math

a = float(input("Digite o primeiro número inteiro: "))
b = float(input("Digite o segundo número inteiro: "))

soma = print("A soma é: ",a + b)
sub = print("A subtração é: ",a - b)
mult = print("O produto dos números digitados é: ",a * b)
div = print("O quociente é: ", a / b)
resto = print("O resto da divisão entre os números diogitados é: ", a % b)
log = print("O resultado de log é: ", math.log(a, 10))
exp = print("Exponenciação: ", a ** b)

